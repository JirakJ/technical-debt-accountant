package com.jakubjirak.debtaccountant.report

import com.jakubjirak.debtaccountant.health.DebtHealthScorer
import com.jakubjirak.debtaccountant.hotspot.HotspotDetector
import com.jakubjirak.debtaccountant.model.DebtCategory
import com.jakubjirak.debtaccountant.model.DebtPriority
import com.jakubjirak.debtaccountant.model.DebtReport
import com.jakubjirak.debtaccountant.model.TechDebtItem
import com.jakubjirak.debtaccountant.valuation.DollarValuator
import com.jakubjirak.debtaccountant.valuation.RoiCalculator
import java.text.SimpleDateFormat
import java.util.Date

class ReportGenerator(private val valuator: DollarValuator = DollarValuator()) {

    private val roiCalculator = RoiCalculator(valuator)
    private val hotspotDetector = HotspotDetector()

    fun generateReport(projectName: String, items: List<TechDebtItem>, currency: String): DebtReport {
        val activeItems = items.filter { !it.isResolved }
        val health = DebtHealthScorer.score(
            items = activeItems,
            monthlyInterest = valuator.totalMonthlyInterest(activeItems)
        )

        return DebtReport(
            projectName = projectName,
            totalItems = items.size,
            resolvedItems = items.count { it.isResolved },
            activeItems = activeItems.size,
            totalWorkaroundCost = valuator.totalWorkaroundCost(activeItems),
            totalFixCost = valuator.totalFixCost(activeItems),
            currency = currency,
            topHotspots = hotspotDetector.detectHotspots(items, 5),
            topRoiOpportunities = roiCalculator.getTopRoiOpportunities(activeItems, 5),
            categoryBreakdown = activeItems.groupBy { it.category }.mapValues { it.value.size },
            priorityBreakdown = activeItems.groupBy { it.priority }.mapValues { it.value.size },
            healthScore = health.score,
            healthGrade = health.grade.letter,
            healthLabel = health.grade.label
        )
    }

    @Suppress("LongMethod")
    fun toMarkdown(report: DebtReport): String {
        val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm")
        val sb = StringBuilder()

        sb.appendLine("# Technical Debt Report — ${report.projectName}")
        sb.appendLine()
        sb.appendLine("*Generated: ${dateFormat.format(Date(report.generatedAt))}*")
        sb.appendLine()

        sb.appendLine("## Executive Summary")
        sb.appendLine()
        sb.appendLine("| Metric | Value |")
        sb.appendLine("|--------|-------|")
        sb.appendLine("| Debt Health Grade | ${report.healthGrade} — ${report.healthLabel} (${report.healthScore}/100) |")
        sb.appendLine("| Active Debt Items | ${report.activeItems} |")
        sb.appendLine("| Resolved Items | ${report.resolvedItems} |")
        sb.appendLine(
            "| Total Workaround Cost | ${valuator.formatCurrency(report.totalWorkaroundCost, report.currency)} |"
        )
        sb.appendLine(
            "| Estimated Fix Cost | ${valuator.formatCurrency(report.totalFixCost, report.currency)} |"
        )
        sb.appendLine()

        if (report.priorityBreakdown.isNotEmpty()) {
            sb.appendLine("## Priority Breakdown")
            sb.appendLine()
            sb.appendLine("| Priority | Count |")
            sb.appendLine("|----------|-------|")
            DebtPriority.entries.forEach { priority ->
                val count = report.priorityBreakdown[priority] ?: 0
                if (count > 0) sb.appendLine("| ${priority.displayName} | $count |")
            }
            sb.appendLine()
        }

        if (report.categoryBreakdown.isNotEmpty()) {
            sb.appendLine("## Category Breakdown")
            sb.appendLine()
            sb.appendLine("| Category | Count |")
            sb.appendLine("|----------|-------|")
            DebtCategory.entries.forEach { category ->
                val count = report.categoryBreakdown[category] ?: 0
                if (count > 0) sb.appendLine("| ${category.displayName} | $count |")
            }
            sb.appendLine()
        }

        appendHotspots(sb, report)
        appendRoiOpportunities(sb, report)

        sb.appendLine("---")
        sb.appendLine("*Generated by Technical Debt Accountant plugin*")

        return sb.toString()
    }

    private fun appendHotspots(sb: StringBuilder, report: DebtReport) {
        if (report.topHotspots.isNotEmpty()) {
            sb.appendLine("## Top Debt Hotspots")
            sb.appendLine()
            sb.appendLine("| File | Debt Items | Workaround (min) | Score |")
            sb.appendLine("|------|:----------:|:-----------------:|:-----:|")
            report.topHotspots.forEach { hotspot ->
                sb.appendLine(
                    "| ${hotspot.filePath} | ${hotspot.debtCount} " +
                        "| ${hotspot.totalWorkaroundMinutes} | ${String.format(java.util.Locale.US, "%.1f", hotspot.score)} |"
                )
            }
            sb.appendLine()
        }
    }

    private fun appendRoiOpportunities(sb: StringBuilder, report: DebtReport) {
        if (report.topRoiOpportunities.isNotEmpty()) {
            sb.appendLine("## Top ROI Opportunities")
            sb.appendLine()
            sb.appendLine("| Item | Fix Cost | Monthly Interest | ROI (months) |")
            sb.appendLine("|------|:--------:|:----------------:|:------------:|")
            report.topRoiOpportunities.forEach { roi ->
                sb.appendLine(
                    "| ${roi.itemId.take(8)}... " +
                        "| ${valuator.formatCurrency(roi.estimatedFixCost, roi.currency)} " +
                        "| ${valuator.formatCurrency(roi.monthlyInterest, roi.currency)} " +
                        "| ${String.format(java.util.Locale.US, "%.1f", roi.roiMonths)} |"
                )
            }
            sb.appendLine()
        }
    }
}
